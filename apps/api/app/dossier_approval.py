"""Owner-approved, source-checked Dossier changes; never trust browser preview data."""

from __future__ import annotations

import hashlib
import re
from typing import Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, ConfigDict, Field, model_validator
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.database import get_database_session
from app.models import Opportunity, OpportunityAttribution, Requirement
from app.opportunities import to_read
from app.opportunity_schemas import OpportunityRead

MetadataField = Literal["title", "company", "location", "employmentType", "salaryText"]
FIELD_LIMITS: dict[str, int] = {
    "title": 200, "company": 160, "location": 200,
    "employmentType": 60, "salaryText": 240,
}
FIELD_COLUMNS = {
    "title": "title", "company": "company", "location": "location",
    "employmentType": "employment_type", "salaryText": "salary_text",
}


class ApprovedMetadata(BaseModel):
    model_config = ConfigDict(extra="forbid")
    field: MetadataField
    value: str = Field(min_length=1, max_length=240)
    sourceExcerpt: str = Field(min_length=1, max_length=1000)

    @model_validator(mode="after")
    def validate_value(self) -> ApprovedMetadata:
        if not self.value.strip() or len(self.value.strip()) > FIELD_LIMITS[self.field]:
            raise ValueError("Approved metadata value violates its field length.")
        if not self.sourceExcerpt.strip():
            raise ValueError("An exact supporting excerpt is required.")
        if self.value.strip().casefold() not in self.sourceExcerpt.casefold():
            raise ValueError("Approved metadata value must occur in its supporting excerpt.")
        return self


class ApprovedTechnology(BaseModel):
    model_config = ConfigDict(extra="forbid")
    value: str = Field(min_length=1, max_length=100)
    sourceExcerpt: str = Field(min_length=1, max_length=1000)

    @model_validator(mode="after")
    def validate_value(self) -> ApprovedTechnology:
        if not self.value.strip() or not self.sourceExcerpt.strip():
            raise ValueError("Technology name and excerpt cannot be blank.")
        if self.value.strip().casefold() not in self.sourceExcerpt.casefold():
            raise ValueError("Technology label must appear in its exact supporting excerpt.")
        return self


class ApprovedRequirement(BaseModel):
    model_config = ConfigDict(extra="forbid")
    text: str = Field(min_length=2, max_length=2000)
    kind: Literal["required", "preferred"]
    sourceExcerpt: str = Field(min_length=1, max_length=2000)

    @model_validator(mode="after")
    def validate_value(self) -> ApprovedRequirement:
        if not self.text.strip() or not self.sourceExcerpt.strip():
            raise ValueError("Reviewed requirement and source excerpt cannot be blank.")
        return self


class ApplyReviewedRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    confirmApply: Literal[True]
    sourceSha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    metadata: list[ApprovedMetadata] = Field(default_factory=list, max_length=5)
    technologies: list[ApprovedTechnology] = Field(default_factory=list, max_length=40)
    requirements: list[ApprovedRequirement] = Field(default_factory=list, max_length=40)

    @model_validator(mode="after")
    def has_unique_selection(self) -> ApplyReviewedRequest:
        if not (self.metadata or self.technologies or self.requirements):
            raise ValueError("Select at least one reviewed suggestion to apply.")
        names = [item.field for item in self.metadata]
        if len(names) != len(set(names)):
            raise ValueError("A metadata field cannot be approved more than once.")
        return self


class ApplyReviewedResult(BaseModel):
    appliedMetadata: list[str]
    skippedMetadata: list[str]
    addedTechnologies: list[str]
    skippedTechnologies: list[str]
    addedRequirements: int
    skippedRequirements: int
    changed: bool
    record: OpportunityRead


def normalized(value: str) -> str:
    return " ".join(value.split()).casefold()


router = APIRouter(prefix="/opportunities", tags=["Dossier / Approval"])


@router.post("/{opportunity_id}/apply-reviewed-extraction", response_model=ApplyReviewedResult)
def apply_reviewed_extraction(
    opportunity_id: UUID,
    payload: ApplyReviewedRequest,
    session: Session = Depends(get_database_session),
) -> ApplyReviewedResult:
    """Apply *only* explicitly approved, source-checked values.

    This does not attest that a preview was generated by an AI provider: the
    client payload is user-reviewed input. Extraction status and model provenance
    are therefore deliberately not altered.
    """
    # Lock the parent row on PostgreSQL so parallel requests serialize and do
    # not create duplicate requirements. SQLite test databases ignore FOR UPDATE.
    record = session.scalar(
        select(Opportunity).where(Opportunity.id == opportunity_id).with_for_update()
    )
    if record is None:
        raise HTTPException(404, "Opportunity not found.")
    actual_hash = hashlib.sha256(record.source_text.encode("utf-8")).hexdigest()
    if payload.sourceSha256 != actual_hash:
        raise HTTPException(409, "Original posting fingerprint changed; review again before applying.")

    # Reject all invalid citations *before* changing anything; one commit only.
    for item in [*payload.metadata, *payload.technologies, *payload.requirements]:
        if item.sourceExcerpt not in record.source_text:
            raise HTTPException(422, "An approved source excerpt is not present in the original posting.")

    applied_metadata: list[str] = []
    skipped_metadata: list[str] = []
    for item in payload.metadata:
        column = FIELD_COLUMNS[item.field]
        existing = getattr(record, column)
        if existing is not None and str(existing).strip():
            # The user's manual entry always wins; this endpoint is fill-only.
            skipped_metadata.append(item.field)
        else:
            setattr(record, column, item.value.strip())
            applied_metadata.append(item.field)
            session.add(OpportunityAttribution(
                opportunity_id=opportunity_id, kind="metadata",
                field_name=item.field, value=item.value.strip(),
                source_excerpt=item.sourceExcerpt, source_sha256=actual_hash,
            ))

    existing_technologies = list(record.technologies or [])
    technology_keys = {normalized(value) for value in existing_technologies}
    added_technologies: list[str] = []
    skipped_technologies: list[str] = []
    for item in payload.technologies:
        name = item.value.strip()
        key = normalized(name)
        if key in technology_keys:
            skipped_technologies.append(name)
        elif len(existing_technologies) >= 40:
            skipped_technologies.append(name)
        else:
            existing_technologies.append(name)
            technology_keys.add(key)
            added_technologies.append(name)
            session.add(OpportunityAttribution(
                opportunity_id=opportunity_id, kind="technology",
                field_name="technologies", value=name,
                source_excerpt=item.sourceExcerpt, source_sha256=actual_hash,
            ))
    if added_technologies:
        record.technologies = existing_technologies

    # Query requirements AFTER taking the opportunity row lock.
    existing = session.scalars(
        select(Requirement).where(Requirement.opportunity_id == opportunity_id)
    ).all()
    keys = {(normalized(row.text), row.kind) for row in existing}
    max_position = max((row.position for row in existing), default=-1)
    added_requirements = 0
    skipped_requirements = 0
    for item in payload.requirements:
        key = (normalized(item.text), item.kind)
        if key in keys:
            skipped_requirements += 1
            continue
        max_position += 1
        session.add(Requirement(
            opportunity_id=opportunity_id,
            position=max_position,
            text=item.text.strip(), kind=item.kind,
            source_excerpt=item.sourceExcerpt,
        ))
        keys.add(key)
        added_requirements += 1

    changed = bool(applied_metadata or added_technologies or added_requirements)
    if changed:
        session.commit()
        session.expire_all()
    else:
        session.rollback()  # Release row lock without a write.
    fresh = session.get(Opportunity, opportunity_id)
    if fresh is None:
        raise HTTPException(404, "Opportunity no longer exists.")
    return ApplyReviewedResult(
        appliedMetadata=applied_metadata,
        skippedMetadata=skipped_metadata,
        addedTechnologies=added_technologies,
        skippedTechnologies=skipped_technologies,
        addedRequirements=added_requirements,
        skippedRequirements=skipped_requirements,
        changed=changed,
        record=to_read(fresh),
    )
